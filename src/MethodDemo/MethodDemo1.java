package MethodDemo;

public class MethodDemo1 {
    public static void main(String[] args) {
        playGame();
    }
    //定义一个方法，用于模拟游戏的流程
    public static void playGame() {
        System.out.println("选人物");
        System.out.println("准备开局");
        System.out.println("游戏开始");
        System.out.println("游戏结束");
    }
}
